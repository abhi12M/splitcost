-- Lockdown: close the "Allow all access" hole on every core table, lock
-- functions to service_role, and make the receipt bucket private.
--
-- After this migration the publishable (anon) key can only connect to
-- realtime broadcast channels. All data access goes through the API
-- routes, which use the service_role key.

-- ============================================================
-- 1. Drop "Allow all access" RLS policies
-- ============================================================

DROP POLICY IF EXISTS "Allow all access to groups" ON public.groups;
DROP POLICY IF EXISTS "Allow all access to expenses" ON public.expenses;
DROP POLICY IF EXISTS "Allow all access to users" ON public.users;
DROP POLICY IF EXISTS "Allow all access to expense participants" ON public.expense_participants;
DROP POLICY IF EXISTS "Allow all access to group members" ON public.group_members;
DROP POLICY IF EXISTS "Allow all access to expense_payers" ON public.expense_payers;

-- ============================================================
-- 2. Revoke all table privileges from anon and authenticated
-- ============================================================

REVOKE ALL ON public.groups FROM anon, authenticated;
REVOKE ALL ON public.expenses FROM anon, authenticated;
REVOKE ALL ON public.users FROM anon, authenticated;
REVOKE ALL ON public.group_members FROM anon, authenticated;
REVOKE ALL ON public.expense_participants FROM anon, authenticated;
REVOKE ALL ON public.expense_payers FROM anon, authenticated;

-- ============================================================
-- 3. Revoke function execution from public, anon and authenticated
-- ============================================================
-- PostgreSQL grants EXECUTE to the public pseudo-role by default, and
-- anon/authenticated inherit from it. Revoking from all three closes it.

REVOKE EXECUTE ON FUNCTION public.create_group_with_members(text, text, text[]) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.cleanup_orphan_users(uuid[]) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.delete_group_and_cleanup_users(uuid) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.load_group_details(uuid) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.load_group_summaries(uuid[]) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.add_expense(uuid, text, numeric, text, uuid, text, text, text, date, jsonb, jsonb, text) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.edit_expense(uuid, uuid, text, numeric, text, uuid, text, text, text, date, jsonb, jsonb, text, bigint, text) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.delete_expense(uuid, text) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.set_expense_attachment_path(uuid, text, text) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.set_expense_category(uuid, text, text, text) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.bump_group_revision(uuid, bigint) FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.increment_blog_view(uuid) FROM public, anon, authenticated;

-- ============================================================
-- 4. Drop storage policies for expense-attachments
-- ============================================================

DROP POLICY IF EXISTS "Allow public read expense attachments" ON storage.objects;
DROP POLICY IF EXISTS "Allow public write expense attachments" ON storage.objects;
DROP POLICY IF EXISTS "Allow public update expense attachments" ON storage.objects;
DROP POLICY IF EXISTS "Allow public delete expense attachments" ON storage.objects;

-- Make the bucket private so files are only accessible via signed URLs
-- generated by the API (service_role).
UPDATE storage.buckets
SET public = false
WHERE id = 'expense-attachments';
